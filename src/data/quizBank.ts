export function generateDynamicQuizForLevel(levelNumber: number, questionsPerLevel = 3): QuizQuestion[] {
  // Pool categories mapping or general difficulty scaling
  const shuffledPool = [...masterQuestionPool].sort(() => Math.random() - 0.5);
  
  // Return questions with randomized option orders
  const selected = shuffledPool.slice(0, questionsPerLevel);

  return selected.map(q => {
    const originalCorrectOption = q.options[q.correctIndex];
    const shuffledOptions = [...q.options].sort(() => Math.random() - 0.5);
    const newCorrectIndex = shuffledOptions.indexOf(originalCorrectOption);

    return {
      ...q,
      options: shuffledOptions,
      correctIndex: newCorrectIndex
    };
  });
}
